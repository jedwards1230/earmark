-- 00014_finding_labels_scorecard.sql — labelled findings and the model
-- scorecards (CONTRACT §2.15 "Labels and scorecards"; design:
-- docs/design/audit-lineage.md "Model quality over time").
--
-- What 13 recorded (judge passes, correction keys, the decision log) is
-- turned into "how good was each model, for us, over time":
--
--   * finding_labels — append-only quality labels on proposed fixes:
--     good | junk | partial | unsure, who labelled (labeler 'kind:name',
--     e.g. 'opus:bakeoff-2026-10', 'human:justin'), which import
--     (label_set) and why. A label is keyed like a finding: correction_key
--     is GENERATED by finding_correction_key() — the same expression as
--     transcript_findings.correction_key (13) — over the chunk revision,
--     original and correction the label is about, so a label joins every
--     finding of every recipe that proposed that fix to that chunk text,
--     past or future. A finding without a chunk hash (legacy) has no key;
--     its label is pinned to finding_id instead. finding_id and chunk_id are
--     plain columns (no foreign key): chunks are a disposable projection and
--     a label must outlive any finding or chunk it was resolved through.
--     UPDATE, DELETE and TRUNCATE are refused; a correction is a new row
--     (see finding_labels_effective). DEBUG_DB_RESET drops the table, which
--     no row trigger sees.
--     Idempotency: dedupe_key, generated, md5 over (label_set, labeler,
--     target, label, reason) and UNIQUE, where the target is the
--     correction_key (or, keyless, the finding_id): the same verdict on the
--     same fix reached through a finding or through its chunk is one row.
--     Re-importing a file inserts nothing; changing a label or its reason
--     inserts a new row. labelled_at (when the label was made — the source's
--     date), finding_id on a keyed label, and how the item was resolved are
--     deliberately not part of it.
--   * finding_labels_effective — the label in force per target (a
--     correction_key, or a keyless finding_id): human labelers ('human:…')
--     outrank every other labeler; among equals the latest labelled_at wins,
--     then the latest row. An 'unsure' in force means unlabelled for
--     precision.
--   * recipe_scorecard — one row per propose recipe that left a finding or a
--     judge pass (plus one NULL-recipe row for unattributed legacy findings).
--   * decide_scorecard — one row per decide recipe that made a decision or
--     an fn_calls call.
--
-- Precision = good / (good + junk + partial): 'partial' (right target, still
-- misspelt) is NOT a usable patch, so it counts against, as the bake-off
-- verdicts scored it; 'unsure' is excluded. Each counts distinct labelled
-- targets, never label rows.
--
-- Additive: one new table, three views, three functions. No ALTER and no
-- backfill; CREATE VIEW takes only ACCESS SHARE on the tables it reads.

-- +goose Up
SET LOCAL lock_timeout = '5s';

-- The 13 correction_key expression, verbatim, as a function: callable by
-- the label import and by the finding_labels generated column. It must stay
-- byte-for-byte equal to transcript_findings.correction_key's expression;
-- TestIntegrationFindingCorrectionKeyMatchesFindings pins that.
-- +goose StatementBegin
CREATE FUNCTION finding_correction_key(chunk_text_sha256 TEXT, original_text TEXT, suggested_correction TEXT)
RETURNS TEXT LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT CASE WHEN chunk_text_sha256 IS NULL THEN NULL
                ELSE md5(chunk_text_sha256 || E'\x1f'
                         || lower(btrim(regexp_replace(original_text,
                                  E'[[:space:]\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+', ' ', 'g'))
                                  COLLATE "und-x-icu")
                         || E'\x1f'
                         || lower(btrim(regexp_replace(COALESCE(suggested_correction, ''),
                                  E'[[:space:]\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]+', ' ', 'g'))
                                  COLLATE "und-x-icu"))
           END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION finding_labels_dedupe_key(label_set TEXT, labeler TEXT, correction_key TEXT,
                                          finding_id UUID, label TEXT, reason TEXT)
RETURNS TEXT LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT md5(label_set || E'\x1f' || labeler
               || E'\x1f' || COALESCE(correction_key, 'finding:' || finding_id::text, '')
               || E'\x1f' || label || E'\x1f' || COALESCE(reason, ''))
$$;
-- +goose StatementEnd

CREATE TABLE finding_labels (
    id                BIGSERIAL   PRIMARY KEY,
    label_set         TEXT        NOT NULL
                      CONSTRAINT finding_labels_set_valid
                      CHECK (label_set ~ '^[A-Za-z0-9][A-Za-z0-9._:/-]*$' AND char_length(label_set) <= 128),
    labeler           TEXT        NOT NULL
                      CONSTRAINT finding_labels_labeler_valid
                      CHECK (labeler ~ '^[a-z][a-z0-9_-]*:[^[:space:]]+$' AND char_length(labeler) <= 128),
    label             TEXT        NOT NULL
                      CONSTRAINT finding_labels_label_valid CHECK (label IN ('good', 'junk', 'partial', 'unsure')),
    reason            TEXT
                      CONSTRAINT finding_labels_reason_length CHECK (char_length(reason) <= 2000),
    chunk_id          UUID,
    chunk_text_sha256 TEXT
                      CONSTRAINT finding_labels_chunk_hash_hex CHECK (chunk_text_sha256 ~ '^[0-9a-f]{64}$'),
    original          TEXT        NOT NULL,
    correction        TEXT        NOT NULL,
    issue_type        TEXT,
    finding_id        UUID,
    -- How the import tied the item to a chunk revision: 'finding' (via a
    -- finding's recorded hash), 'hash' (the item named the hash) or 'chunk'
    -- (the current chunk, with the item's span — and context, when given —
    -- found in its text).
    resolved_by       TEXT        NOT NULL
                      CONSTRAINT finding_labels_resolved_by_valid CHECK (resolved_by IN ('finding', 'hash', 'chunk')),
    source_ref        TEXT,
    labelled_at       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    correction_key    TEXT        GENERATED ALWAYS AS
                      (finding_correction_key(chunk_text_sha256, original, correction)) STORED,
    dedupe_key        TEXT        GENERATED ALWAYS AS
                      (finding_labels_dedupe_key(label_set, labeler,
                           finding_correction_key(chunk_text_sha256, original, correction),
                           finding_id, label, reason)) STORED,
    -- A label is about a chunk revision, or (legacy, no hash) one finding.
    CONSTRAINT finding_labels_target CHECK (chunk_text_sha256 IS NOT NULL OR finding_id IS NOT NULL)
);

CREATE UNIQUE INDEX finding_labels_dedupe_idx ON finding_labels (dedupe_key);
-- The scorecard joins: labels by fix, and keyless labels by finding.
CREATE INDEX finding_labels_correction_key_idx ON finding_labels (correction_key, labelled_at DESC, id DESC);
CREATE INDEX finding_labels_finding_idx ON finding_labels (finding_id) WHERE correction_key IS NULL;
CREATE INDEX finding_labels_set_idx ON finding_labels (label_set, labeler);

-- +goose StatementBegin
CREATE FUNCTION finding_labels_append_only() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'finding_labels is append-only: % refused (import a newer label instead)', TG_OP
        USING ERRCODE = 'restrict_violation';
END $$;
-- +goose StatementEnd

CREATE TRIGGER finding_labels_append_only
    BEFORE UPDATE OR DELETE ON finding_labels
    FOR EACH ROW EXECUTE FUNCTION finding_labels_append_only();

-- TRUNCATE fires no row trigger: refuse it with a statement trigger.
CREATE TRIGGER finding_labels_no_truncate
    BEFORE TRUNCATE ON finding_labels
    FOR EACH STATEMENT EXECUTE FUNCTION finding_labels_append_only();

-- The label in force per target. finding_id is set only for keyless
-- (legacy, no chunk hash) labels; a keyed label applies to its fix.
CREATE VIEW finding_labels_effective AS
SELECT DISTINCT ON (COALESCE(l.correction_key, l.finding_id::text))
       l.correction_key,
       CASE WHEN l.correction_key IS NULL THEN l.finding_id END AS finding_id,
       l.label, l.labeler, l.label_set, l.labelled_at, l.id AS label_id
  FROM finding_labels l
 ORDER BY COALESCE(l.correction_key, l.finding_id::text),
          (l.labeler LIKE 'human:%') DESC, l.labelled_at DESC, l.id DESC;

-- One row per propose recipe. Columns that only a recorded (non-legacy)
-- judge pass or a logged judge call can fill — chunk counters, cost,
-- latency, drop counts, parse failures — are NULL for a recipe that has
-- neither (legacy = true): gemma/haiku/qwen-era recipes never recorded them.
--
--   decisions: per decide recipe, the outcome of that recipe's latest live
--   (unrevoked) decision on each of this recipe's findings.
--   applied_ever / reverted: findings with a transition to applied or
--   reverted (a reverted finding was applied first) / those reverted.
--   agreement: share of this recipe's correction_keys that a recipe of
--   another configuration (not equivalent, §1.9) also proposed.
--   Unattributed (NULL-recipe) findings never count as a partner.
CREATE VIEW recipe_scorecard AS
WITH f AS MATERIALIZED (
    SELECT f.id, f.recipe_id, f.issue_type, f.patch_state, f.correction_key, f.created_at
      FROM transcript_findings f
     WHERE f.origin = 'judge'
),
rc AS (
    SELECT r.recipe_id,
           md5(ROW(r.step, r.step_version, r.model_alias, r.model_resolved, r.model_revision,
                   r.prompt_version, r.prompt_sha256, r.params)::text) AS cls
      FROM recipes r
),
fs AS (
    SELECT recipe_id,
           count(*) AS findings_total,
           count(*) FILTER (WHERE patch_state <> 'superseded') AS findings_live,
           min(created_at) AS first_finding_at,
           max(created_at) AS last_finding_at
      FROM f GROUP BY recipe_id
),
issue AS (
    SELECT recipe_id, jsonb_object_agg(issue_type, n) AS issue_mix
      FROM (SELECT recipe_id, issue_type, count(*) AS n FROM f GROUP BY 1, 2) x
     GROUP BY recipe_id
),
states AS (
    SELECT recipe_id, jsonb_object_agg(patch_state, n) AS state_mix
      FROM (SELECT recipe_id, patch_state, count(*) AS n FROM f GROUP BY 1, 2) x
     GROUP BY recipe_id
),
jp AS (
    SELECT p.recipe_id,
           count(*) AS passes,
           count(*) FILTER (WHERE p.status = 'complete') AS passes_complete,
           count(*) FILTER (WHERE p.status = 'legacy') AS passes_legacy,
           count(*) FILTER (WHERE p.status IN ('partial', 'failed')) AS passes_incomplete,
           count(*) FILTER (WHERE p.status = 'running') AS passes_running,
           count(DISTINCT p.transcript_id) FILTER (WHERE p.status IN ('complete', 'legacy')) AS transcripts_judged,
           bool_or(p.status <> 'legacy') AS recorded,
           sum(p.chunks_judged) FILTER (WHERE p.status <> 'legacy') AS chunks_judged,
           sum(p.chunks_cached) FILTER (WHERE p.status <> 'legacy') AS chunks_cached,
           sum(p.chunks_failed) FILTER (WHERE p.status <> 'legacy') AS chunks_failed,
           sum(p.findings_kept) FILTER (WHERE p.status <> 'legacy' AND p.chunks_judged IS NOT NULL) AS findings_kept,
           sum(p.cost_usd) FILTER (WHERE p.status <> 'legacy') AS cost_usd,
           sum(p.chunks_judged) FILTER (WHERE p.status <> 'legacy' AND p.cost_usd IS NOT NULL) AS costed_chunks,
           sum(p.latency_ms_p50::float8 * p.chunks_judged)
               FILTER (WHERE p.status <> 'legacy' AND p.latency_ms_p50 IS NOT NULL)
             / NULLIF(sum(p.chunks_judged)
               FILTER (WHERE p.status <> 'legacy' AND p.latency_ms_p50 IS NOT NULL), 0) AS pass_latency_ms_p50,
           sum(p.latency_ms_p95::float8 * p.chunks_judged)
               FILTER (WHERE p.status <> 'legacy' AND p.latency_ms_p95 IS NOT NULL)
             / NULLIF(sum(p.chunks_judged)
               FILTER (WHERE p.status <> 'legacy' AND p.latency_ms_p95 IS NOT NULL), 0) AS pass_latency_ms_p95,
           bool_or(p.dropped IS NOT NULL) AS drops_recorded,
           min(p.started_at) AS first_pass_at,
           max(COALESCE(p.finished_at, p.started_at)) AS last_pass_at
      FROM judge_passes p
     GROUP BY p.recipe_id
),
drops AS (
    SELECT recipe_id, jsonb_object_agg(reason, n) AS drops
      FROM (SELECT p.recipe_id, d.key AS reason, sum(d.value::numeric)::bigint AS n
              FROM judge_passes p
              CROSS JOIN LATERAL jsonb_each_text(p.dropped) d
             WHERE p.status <> 'legacy'
             GROUP BY 1, 2) x
     GROUP BY recipe_id
),
calls AS (
    SELECT c.recipe_id,
           count(*) FILTER (WHERE c.error_class = 'invalid_reply') AS parse_failures,
           percentile_cont(0.5) WITHIN GROUP (ORDER BY c.latency_ms)
               FILTER (WHERE NOT c.cache_hit AND c.error_class IS NULL) AS call_latency_ms_p50,
           percentile_cont(0.95) WITHIN GROUP (ORDER BY c.latency_ms)
               FILTER (WHERE NOT c.cache_hit AND c.error_class IS NULL) AS call_latency_ms_p95
      FROM fn_calls c
     WHERE c.fn = 'judge_chunk'
     GROUP BY c.recipe_id
),
dec AS (
    SELECT DISTINCT ON (e.finding_id, e.recipe_id)
           e.finding_id, e.recipe_id, e.outcome, COALESCE(e.reason, '') AS reason
      FROM finding_events e
     WHERE e.kind = 'decision'
       AND NOT EXISTS (SELECT 1 FROM finding_events v
                        WHERE v.kind = 'revoke' AND v.revokes_event_id = e.id)
     ORDER BY e.finding_id, e.recipe_id, e.id DESC
),
dg AS (
    SELECT f.recipe_id, d.recipe_id AS decide_recipe_id, d.outcome, d.reason, count(*) AS n
      FROM dec d
      JOIN f ON f.id = d.finding_id
     GROUP BY 1, 2, 3, 4
),
dd AS (
    SELECT dg.recipe_id, dg.decide_recipe_id,
           sum(n)::bigint AS decided,
           COALESCE(sum(n) FILTER (WHERE outcome = 'apply'), 0)::bigint AS apply,
           COALESCE(sum(n) FILTER (WHERE outcome = 'hold'), 0)::bigint AS hold,
           COALESCE(sum(n) FILTER (WHERE outcome = 'reject'), 0)::bigint AS reject,
           jsonb_object_agg(outcome || ':' || reason, n) AS reasons
      FROM dg
     GROUP BY 1, 2
),
decs AS (
    SELECT dd.recipe_id,
           jsonb_agg(jsonb_build_object(
               'decide_recipe_id', dd.decide_recipe_id, 'decide_model', r.model_alias,
               'decided', dd.decided, 'apply', dd.apply, 'hold', dd.hold, 'reject', dd.reject,
               'reasons', dd.reasons) ORDER BY dd.decide_recipe_id) AS decisions
      FROM dd
      LEFT JOIN recipes r ON r.recipe_id = dd.decide_recipe_id
     GROUP BY dd.recipe_id
),
tr AS (
    SELECT e.finding_id, bool_or(e.to_state = 'reverted') AS reverted
      FROM finding_events e
     WHERE e.kind = 'transition' AND e.to_state IN ('applied', 'reverted')
     GROUP BY e.finding_id
),
rv AS (
    SELECT f.recipe_id, count(*) AS applied_ever, count(*) FILTER (WHERE tr.reverted) AS reverted
      FROM tr JOIN f ON f.id = tr.finding_id
     GROUP BY f.recipe_id
),
kr AS (
    SELECT DISTINCT f.correction_key, f.recipe_id, rc.cls
      FROM f LEFT JOIN rc ON rc.recipe_id = f.recipe_id
     WHERE f.correction_key IS NOT NULL
),
kc AS (
    SELECT correction_key, count(DISTINCT cls) AS classes FROM kr GROUP BY correction_key
),
agree AS (
    SELECT kr.recipe_id, count(*) AS correction_keys,
           count(*) FILTER (WHERE kc.classes > CASE WHEN kr.cls IS NULL THEN 0 ELSE 1 END) AS agreed_keys
      FROM kr JOIN kc ON kc.correction_key = kr.correction_key
     GROUP BY kr.recipe_id
),
fl AS (
    SELECT * FROM (
        SELECT DISTINCT ON (f.recipe_id, f.correction_key) f.recipe_id, f.issue_type, el.label
          FROM f JOIN finding_labels_effective el ON el.correction_key = f.correction_key
         ORDER BY f.recipe_id, f.correction_key, f.created_at, f.id
    ) k
    UNION ALL
    SELECT f.recipe_id, f.issue_type, el.label
      FROM f JOIN finding_labels_effective el ON el.finding_id = f.id
     WHERE f.correction_key IS NULL
),
lab AS (
    SELECT recipe_id,
           count(*) FILTER (WHERE label = 'good') AS good,
           count(*) FILTER (WHERE label = 'junk') AS junk,
           count(*) FILTER (WHERE label = 'partial') AS partial,
           count(*) FILTER (WHERE label = 'unsure') AS unsure,
           count(*) FILTER (WHERE label = 'good' AND issue_type = 'misheard_proper_noun') AS pn_good,
           count(*) FILTER (WHERE label = 'junk' AND issue_type = 'misheard_proper_noun') AS pn_junk,
           count(*) FILTER (WHERE label = 'partial' AND issue_type = 'misheard_proper_noun') AS pn_partial,
           count(*) FILTER (WHERE label = 'unsure' AND issue_type = 'misheard_proper_noun') AS pn_unsure
      FROM fl GROUP BY recipe_id
),
props AS (
    SELECT recipe_id FROM fs
    UNION
    SELECT recipe_id FROM jp
)
SELECT p.recipe_id,
       r.model_alias, r.model_resolved, r.prompt_version, r.step_version,
       r.created_at AS recipe_created_at,
       NOT COALESCE(jp.recorded, false) AND calls.recipe_id IS NULL AS legacy,
       COALESCE(jp.passes, 0)::bigint AS passes,
       COALESCE(jp.passes_complete, 0)::bigint AS passes_complete,
       COALESCE(jp.passes_legacy, 0)::bigint AS passes_legacy,
       COALESCE(jp.passes_incomplete, 0)::bigint AS passes_incomplete,
       COALESCE(jp.passes_running, 0)::bigint AS passes_running,
       COALESCE(jp.transcripts_judged, 0)::bigint AS transcripts_judged,
       jp.chunks_judged::bigint AS chunks_judged,
       jp.chunks_cached::bigint AS chunks_cached,
       jp.chunks_failed::bigint AS chunks_failed,
       (jp.chunks_cached::float8 / NULLIF(jp.chunks_judged, 0)) AS cached_share,
       COALESCE(fs.findings_total, 0)::bigint AS findings_total,
       COALESCE(fs.findings_live, 0)::bigint AS findings_live,
       (jp.findings_kept * 1000.0 / NULLIF(jp.chunks_judged, 0))::float8 AS findings_per_1k_chunks,
       COALESCE(issue.issue_mix, '{}'::jsonb) AS issue_mix,
       COALESCE(states.state_mix, '{}'::jsonb) AS state_mix,
       CASE WHEN jp.drops_recorded THEN COALESCE(drops.drops, '{}'::jsonb) END AS drops,
       calls.parse_failures::bigint AS parse_failures,
       COALESCE(decs.decisions, '[]'::jsonb) AS decisions,
       COALESCE(rv.applied_ever, 0)::bigint AS applied_ever,
       COALESCE(rv.reverted, 0)::bigint AS reverted,
       (rv.reverted::float8 / NULLIF(rv.applied_ever, 0)) AS revert_rate,
       COALESCE(agree.correction_keys, 0)::bigint AS correction_keys,
       COALESCE(agree.agreed_keys, 0)::bigint AS agreed_keys,
       (agree.agreed_keys::float8 / NULLIF(agree.correction_keys, 0)) AS agreement_rate,
       COALESCE(lab.good, 0)::bigint AS labelled_good,
       COALESCE(lab.junk, 0)::bigint AS labelled_junk,
       COALESCE(lab.partial, 0)::bigint AS labelled_partial,
       COALESCE(lab.unsure, 0)::bigint AS labelled_unsure,
       (lab.good::float8 / NULLIF(lab.good + lab.junk + lab.partial, 0)) AS label_precision,
       COALESCE(lab.pn_good, 0)::bigint AS proper_noun_good,
       COALESCE(lab.pn_junk, 0)::bigint AS proper_noun_junk,
       COALESCE(lab.pn_partial, 0)::bigint AS proper_noun_partial,
       COALESCE(lab.pn_unsure, 0)::bigint AS proper_noun_unsure,
       (lab.pn_good::float8 / NULLIF(lab.pn_good + lab.pn_junk + lab.pn_partial, 0)) AS proper_noun_precision,
       jp.cost_usd::float8 AS cost_usd,
       (jp.cost_usd / NULLIF(jp.costed_chunks, 0))::float8 AS cost_per_chunk_usd,
       COALESCE(calls.call_latency_ms_p50, jp.pass_latency_ms_p50) AS latency_ms_p50,
       COALESCE(calls.call_latency_ms_p95, jp.pass_latency_ms_p95) AS latency_ms_p95,
       CASE WHEN calls.call_latency_ms_p50 IS NOT NULL THEN 'calls'
            WHEN jp.pass_latency_ms_p50 IS NOT NULL THEN 'passes' END AS latency_source,
       LEAST(fs.first_finding_at, jp.first_pass_at) AS first_activity_at,
       GREATEST(fs.last_finding_at, jp.last_pass_at) AS last_activity_at
  FROM props p
  LEFT JOIN recipes r     ON r.recipe_id = p.recipe_id
  LEFT JOIN fs            ON fs.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN issue         ON issue.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN states        ON states.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN jp            ON jp.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN drops         ON drops.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN calls         ON calls.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN decs          ON decs.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN rv            ON rv.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN agree         ON agree.recipe_id IS NOT DISTINCT FROM p.recipe_id
  LEFT JOIN lab           ON lab.recipe_id IS NOT DISTINCT FROM p.recipe_id;

-- One row per decide recipe.
--
--   live: each finding's latest unrevoked decision by this recipe. Outcome ×
--   evidence, reasons, the label and human comparisons read it.
--   label_calibration / human_calibration: live decisions with a p, in five
--   p buckets of 0.2 (bucket 1 = [0, 0.2) … bucket 5 = [0.8, 1]), against the
--   label in force and against the human decision on the finding
--   (decided_by 'mcp:…': accepted/applied = accept, rejected/reverted =
--   reject).
--   human_agree: live apply decisions a human accepted plus live rejects a
--   human rejected, of human_decided (live applies and rejects with a human
--   decision).
--   flips: of the findings both this recipe and the previous decide recipe
--   decided (each recipe's latest decision, revoked or not), how many got a
--   different outcome. "Previous" is the non-equivalent decide recipe whose
--   first decision is the latest before this recipe's first.
--   calls / cost / latency: this recipe's fn_calls rows (dry runs included).
CREATE VIEW decide_scorecard AS
WITH rvk AS (
    SELECT revokes_event_id FROM finding_events WHERE kind = 'revoke'
),
ev AS MATERIALIZED (
    SELECT e.id, e.finding_id, e.recipe_id, e.outcome, COALESCE(e.reason, '') AS reason, e.p,
           COALESCE(e.evidence, 'unassessed') AS evidence, e.created_at,
           (rvk.revokes_event_id IS NOT NULL) AS revoked
      FROM finding_events e
      LEFT JOIN rvk ON rvk.revokes_event_id = e.id
     WHERE e.kind = 'decision'
),
latest AS MATERIALIZED (
    SELECT DISTINCT ON (finding_id, recipe_id) finding_id, recipe_id, outcome
      FROM ev ORDER BY finding_id, recipe_id, id DESC
),
live AS MATERIALIZED (
    SELECT DISTINCT ON (ev.finding_id, ev.recipe_id)
           ev.finding_id, ev.recipe_id, ev.outcome, ev.reason, ev.p, ev.evidence,
           f.correction_key, f.decided_by, f.patch_state
      FROM ev
      JOIN transcript_findings f ON f.id = ev.finding_id
     WHERE NOT ev.revoked
     ORDER BY ev.finding_id, ev.recipe_id, ev.id DESC
),
rc AS (
    SELECT r.recipe_id,
           md5(ROW(r.step, r.step_version, r.model_alias, r.model_resolved, r.model_revision,
                   r.prompt_version, r.prompt_sha256, r.params)::text) AS cls
      FROM recipes r
     WHERE r.step = 'decide'
),
ds AS (
    SELECT recipe_id, count(*) AS decisions, count(*) FILTER (WHERE revoked) AS revoked,
           count(DISTINCT finding_id) AS findings_decided,
           min(created_at) AS first_decision_at, max(created_at) AS last_decision_at
      FROM ev GROUP BY recipe_id
),
oc AS (
    SELECT recipe_id, count(*) AS live,
           count(*) FILTER (WHERE outcome = 'apply') AS apply,
           count(*) FILTER (WHERE outcome = 'hold') AS hold,
           count(*) FILTER (WHERE outcome = 'reject') AS reject
      FROM live GROUP BY recipe_id
),
oe AS (
    SELECT recipe_id, jsonb_object_agg(outcome, mix) AS outcome_evidence
      FROM (SELECT recipe_id, outcome, jsonb_object_agg(evidence, n) AS mix
              FROM (SELECT recipe_id, outcome, evidence, count(*) AS n FROM live GROUP BY 1, 2, 3) a
             GROUP BY 1, 2) b
     GROUP BY recipe_id
),
rs AS (
    SELECT recipe_id, jsonb_object_agg(outcome || ':' || reason, n) AS reasons
      FROM (SELECT recipe_id, outcome, reason, count(*) AS n FROM live GROUP BY 1, 2, 3) a
     GROUP BY recipe_id
),
ll AS (
    SELECT l.recipe_id, l.outcome, l.p, el.label
      FROM live l JOIN finding_labels_effective el ON el.correction_key = l.correction_key
    UNION ALL
    SELECT l.recipe_id, l.outcome, l.p, el.label
      FROM live l JOIN finding_labels_effective el ON el.finding_id = l.finding_id
     WHERE l.correction_key IS NULL
),
lo AS (
    SELECT recipe_id, jsonb_object_agg(outcome, jsonb_build_object(
               'good', good, 'junk', junk, 'partial', partial, 'unsure', unsure)) AS label_outcomes
      FROM (SELECT recipe_id, outcome,
                   count(*) FILTER (WHERE label = 'good') AS good,
                   count(*) FILTER (WHERE label = 'junk') AS junk,
                   count(*) FILTER (WHERE label = 'partial') AS partial,
                   count(*) FILTER (WHERE label = 'unsure') AS unsure
              FROM ll GROUP BY 1, 2) a
     GROUP BY recipe_id
),
lcal AS (
    SELECT recipe_id, jsonb_agg(jsonb_build_object(
               'bucket', b, 'good', good, 'junk', junk, 'partial', partial, 'unsure', unsure)
               ORDER BY b) AS label_calibration
      FROM (SELECT recipe_id, LEAST(width_bucket(p, 0, 1, 5), 5) AS b,
                   count(*) FILTER (WHERE label = 'good') AS good,
                   count(*) FILTER (WHERE label = 'junk') AS junk,
                   count(*) FILTER (WHERE label = 'partial') AS partial,
                   count(*) FILTER (WHERE label = 'unsure') AS unsure
              FROM ll WHERE p IS NOT NULL GROUP BY 1, 2) a
     GROUP BY recipe_id
),
hl AS (
    SELECT recipe_id, outcome, p, patch_state IN ('accepted', 'applied') AS human_accept
      FROM live
     WHERE decided_by ~ '^mcp:'
       AND patch_state IN ('accepted', 'applied', 'rejected', 'reverted')
),
hcal AS (
    SELECT recipe_id, jsonb_agg(jsonb_build_object(
               'bucket', b, 'accepted', accepted, 'rejected', rejected) ORDER BY b) AS human_calibration
      FROM (SELECT recipe_id, LEAST(width_bucket(p, 0, 1, 5), 5) AS b,
                   count(*) FILTER (WHERE human_accept) AS accepted,
                   count(*) FILTER (WHERE NOT human_accept) AS rejected
              FROM hl WHERE p IS NOT NULL GROUP BY 1, 2) a
     GROUP BY recipe_id
),
hag AS (
    SELECT recipe_id,
           count(*) FILTER (WHERE outcome IN ('apply', 'reject')) AS human_decided,
           count(*) FILTER (WHERE (outcome = 'apply' AND human_accept)
                               OR (outcome = 'reject' AND NOT human_accept)) AS human_agree
      FROM hl GROUP BY recipe_id
),
firsts AS (
    SELECT ds.recipe_id, ds.first_decision_at, rc.cls
      FROM ds JOIN rc ON rc.recipe_id = ds.recipe_id
),
prev AS (
    SELECT a.recipe_id,
           (SELECT b.recipe_id FROM firsts b
             WHERE b.first_decision_at < a.first_decision_at AND b.cls <> a.cls
             ORDER BY b.first_decision_at DESC, b.recipe_id DESC LIMIT 1) AS prev_recipe_id
      FROM firsts a
),
flip AS (
    SELECT pv.recipe_id, count(*) AS overlap, count(*) FILTER (WHERE x.outcome <> y.outcome) AS flips
      FROM prev pv
      JOIN latest x ON x.recipe_id = pv.recipe_id
      JOIN latest y ON y.recipe_id = pv.prev_recipe_id AND y.finding_id = x.finding_id
     GROUP BY pv.recipe_id
),
calls AS (
    SELECT c.recipe_id,
           count(*) FILTER (WHERE NOT c.cache_hit AND c.error_class IS NULL) AS calls,
           count(*) FILTER (WHERE c.cache_hit) AS calls_cached,
           count(*) FILTER (WHERE c.error_class IS NOT NULL) AS call_errors,
           sum(c.cost_usd) FILTER (WHERE NOT c.cache_hit) AS cost_usd,
           percentile_cont(0.5) WITHIN GROUP (ORDER BY c.latency_ms)
               FILTER (WHERE NOT c.cache_hit AND c.error_class IS NULL) AS latency_ms_p50,
           percentile_cont(0.95) WITHIN GROUP (ORDER BY c.latency_ms)
               FILTER (WHERE NOT c.cache_hit AND c.error_class IS NULL) AS latency_ms_p95,
           max(c.created_at) AS last_call_at
      FROM fn_calls c
      JOIN rc ON rc.recipe_id = c.recipe_id
     GROUP BY c.recipe_id
),
recs AS (
    SELECT recipe_id FROM ds
    UNION
    SELECT recipe_id FROM calls
)
SELECT d.recipe_id,
       r.model_alias, r.model_resolved, r.prompt_version, r.step_version, r.params,
       r.created_at AS recipe_created_at,
       COALESCE(ds.decisions, 0)::bigint AS decisions,
       COALESCE(ds.revoked, 0)::bigint AS revoked,
       (ds.revoked::float8 / NULLIF(ds.decisions, 0)) AS revoke_rate,
       COALESCE(ds.findings_decided, 0)::bigint AS findings_decided,
       COALESCE(oc.live, 0)::bigint AS live,
       COALESCE(oc.apply, 0)::bigint AS apply,
       COALESCE(oc.hold, 0)::bigint AS hold,
       COALESCE(oc.reject, 0)::bigint AS reject,
       COALESCE(oe.outcome_evidence, '{}'::jsonb) AS outcome_evidence,
       COALESCE(rs.reasons, '{}'::jsonb) AS reasons,
       COALESCE(lo.label_outcomes, '{}'::jsonb) AS label_outcomes,
       COALESCE(lcal.label_calibration, '[]'::jsonb) AS label_calibration,
       COALESCE(hcal.human_calibration, '[]'::jsonb) AS human_calibration,
       COALESCE(hag.human_decided, 0)::bigint AS human_decided,
       COALESCE(hag.human_agree, 0)::bigint AS human_agree,
       (hag.human_agree::float8 / NULLIF(hag.human_decided, 0)) AS human_agreement,
       prev.prev_recipe_id,
       COALESCE(flip.overlap, 0)::bigint AS flip_overlap,
       COALESCE(flip.flips, 0)::bigint AS flips,
       (flip.flips::float8 / NULLIF(flip.overlap, 0)) AS flip_rate,
       COALESCE(calls.calls, 0)::bigint AS calls,
       COALESCE(calls.calls_cached, 0)::bigint AS calls_cached,
       COALESCE(calls.call_errors, 0)::bigint AS call_errors,
       calls.cost_usd::float8 AS cost_usd,
       (calls.cost_usd / NULLIF(calls.calls, 0))::float8 AS cost_per_call_usd,
       calls.latency_ms_p50,
       calls.latency_ms_p95,
       ds.first_decision_at,
       GREATEST(ds.last_decision_at, calls.last_call_at) AS last_activity_at
  FROM recs d
  JOIN recipes r     ON r.recipe_id = d.recipe_id
  LEFT JOIN ds       ON ds.recipe_id = d.recipe_id
  LEFT JOIN oc       ON oc.recipe_id = d.recipe_id
  LEFT JOIN oe       ON oe.recipe_id = d.recipe_id
  LEFT JOIN rs       ON rs.recipe_id = d.recipe_id
  LEFT JOIN lo       ON lo.recipe_id = d.recipe_id
  LEFT JOIN lcal     ON lcal.recipe_id = d.recipe_id
  LEFT JOIN hcal     ON hcal.recipe_id = d.recipe_id
  LEFT JOIN hag      ON hag.recipe_id = d.recipe_id
  LEFT JOIN prev     ON prev.recipe_id = d.recipe_id
  LEFT JOIN flip     ON flip.recipe_id = d.recipe_id
  LEFT JOIN calls    ON calls.recipe_id = d.recipe_id;


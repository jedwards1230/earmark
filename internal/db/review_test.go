// reviewSQL is the set of statements the REVIEWER surface (review.go) issues.
// Kept separate from corrections_test.go's correctionSQL map because these are
// this file's own package vars — the two maps are merged for the shared
// provenance guard in corrections_test.go.
var reviewSQL = map[string]string{
	"listCorrectionsSQL":        listCorrectionsSQL,
	"chunkTargetSQL":            chunkTargetSQL,
	"insertManualCorrectionSQL": insertManualCorrectionSQL,
	"markChunkStaleByIDSQL":     markChunkStaleByIDSQL,
}

// TestListCorrectionsSQL_ReadOnlyAndPristine pins the reviewer worklist query:
// read-only, and selects the PRISTINE chunk text — the same text an anchor
// must be resolved against, never the corrected surface.
func TestListCorrectionsSQL_ReadOnlyAndPristine(t *testing.T) {
	if !strings.HasPrefix(strings.TrimSpace(strings.ToUpper(listCorrectionsSQL)), "SELECT") {
		t.Errorf("listCorrectionsSQL must start with SELECT:\n%s", listCorrectionsSQL)
	}
	if !strings.Contains(listCorrectionsSQL, "COALESCE(c.source_text, c.text, '')") {
		t.Errorf("listCorrectionsSQL must select the pristine chunk text:\n%s", listCorrectionsSQL)
	}
}

// TestChunkTargetSQL_ReadOnlyAndPristine pins the direct-edit chunk read: it

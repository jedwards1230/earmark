// TestInsertManualCorrection_Success asserts the happy path runs the guarded
// INSERT, then the stale UPDATE, then commits — in one transaction — and
// propagates the returned id.
func TestInsertManualCorrection_Success(t *testing.T) {
	database := newTestDB()
	mock, err := pgxmock.NewPool()
	if err != nil {
		t.Fatalf("new mock pool: %v", err)
	}
	defer mock.Close()

	m := ManualCorrection{
		ChunkID: "c1", OriginalText: "auto sebo", Correction: "Arecibo",
		AnchorOffset: 21, AnchorOccurrence: 0,
		ChunkSHA256: patch.ChunkHash("the auto sebo dish"),
		IssueType:   "misheard_proper_noun", DecidedBy: "mcp:justin",
	}

	mock.ExpectBegin()
	mock.ExpectQuery("INSERT INTO transcript_findings").
		WithArgs(m.ChunkID, m.OriginalText, m.IssueType, m.Correction,
			ManualEditConfidence, ManualEditModel,
			OriginHuman, patch.StateAccepted, m.DecidedBy,
			m.AnchorOffset, m.AnchorOccurrence, m.ChunkSHA256).
		WillReturnRows(pgxmock.NewRows([]string{"id"}).AddRow("new-finding-id"))
	mock.ExpectExec("UPDATE transcript_chunks").
		WithArgs(m.ChunkID).
		WillReturnResult(pgxmock.NewResult("UPDATE", 1))
	mock.ExpectCommit()

	id, err := database.insertManualCorrection(context.Background(), mock, m)
	if err != nil {
		t.Fatalf("insertManualCorrection: %v", err)
	}
	if id != "new-finding-id" {
		t.Errorf("id: want %q, got %q", "new-finding-id", id)
	}
	if err := mock.ExpectationsWereMet(); err != nil {
		t.Errorf("unmet expectations: %v", err)
	}
}

// TestInsertManualCorrection_ChunkChangedRefusesWithoutStaleUpdateOrCommit
// asserts the guarded INSERT matching zero rows (pgx.ErrNoRows) is translated
// to patch.ErrChunkChanged, and that neither the stale UPDATE nor the commit
// ever run — only Begin, the failed INSERT, and the deferred Rollback.
func TestInsertManualCorrection_ChunkChangedRefusesWithoutStaleUpdateOrCommit(t *testing.T) {
	database := newTestDB()
	mock, err := pgxmock.NewPool()
	if err != nil {
		t.Fatalf("new mock pool: %v", err)
	}
	defer mock.Close()

	m := ManualCorrection{
		ChunkID: "c1", OriginalText: "auto sebo", Correction: "Arecibo",
		AnchorOffset: 21, AnchorOccurrence: 0,
		ChunkSHA256: "stale-hash-the-chunk-moved-past",
		IssueType:   "misheard_proper_noun", DecidedBy: "mcp:justin",
	}

	mock.ExpectBegin()
	mock.ExpectQuery("INSERT INTO transcript_findings").
		WithArgs(m.ChunkID, m.OriginalText, m.IssueType, m.Correction,
			ManualEditConfidence, ManualEditModel,
			OriginHuman, patch.StateAccepted, m.DecidedBy,
			m.AnchorOffset, m.AnchorOccurrence, m.ChunkSHA256).
		WillReturnError(pgx.ErrNoRows)
	mock.ExpectRollback()

	_, err = database.insertManualCorrection(context.Background(), mock, m)
	if !errors.Is(err, patch.ErrChunkChanged) {
		t.Fatalf("want patch.ErrChunkChanged, got %v", err)
	}
	// If the code had gone on to run the stale UPDATE or COMMIT, those calls
	// would have no matching expectation (only Begin/Query/Rollback are
	// registered) and ExpectationsWereMet would report the queue unmet/violated.
	if err := mock.ExpectationsWereMet(); err != nil {
		t.Errorf("unmet expectations (stale UPDATE or commit must not have run): %v", err)
	}
}

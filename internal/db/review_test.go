// TestListCorrections_ScansRowsIncludingNullableColumns drives the real
// query + scan path against a mock pool, asserting every column lands in the
// right field — including the nullable columns via pointers.
func TestListCorrections_ScansRowsIncludingNullableColumns(t *testing.T) {
	database := newTestDB()
	mock, err := pgxmock.NewPool()
	if err != nil {
		t.Fatalf("new mock pool: %v", err)
	}
	defer mock.Close()

	chunkID := "chunk-1"
	chunkIdx := 3
	correction := "Arecibo"
	staleReason := "chunk_changed"
	decidedAt := time.Date(2026, 8, 19, 12, 0, 0, 0, time.UTC)
	decidedBy := "mcp:agent"
	appliedAt := time.Date(2026, 8, 19, 13, 0, 0, 0, time.UTC)
	createdAt := time.Date(2026, 8, 18, 10, 0, 0, 0, time.UTC)
	off, occ := 21, 0
	hash := patch.ChunkHash("the auto sebo dish")

	rows := pgxmock.NewRows(correctionDetailColumns).
		AddRow(
			"f1", "t1", "/books/a/b/ch1.m4b", "/books/a/b",
			&chunkID, &chunkIdx, 73.5, 81.0,
			"auto sebo", &correction, "misheard_proper_noun", 0.92,
			"qwen2.5-14b-instruct", OriginJudge, patch.StateProposed, &staleReason,
			&decidedAt, &decidedBy, &appliedAt, createdAt,
			&off, &occ, &hash,
			"the auto sebo dish",
		).
		// Second row exercises the NULLable columns as nil.
		AddRow(
			"f2", "t1", "/books/a/b/ch2.m4b", "/books/a/b",
			(*string)(nil), (*int)(nil), 0.0, 0.0,
			"pin name", (*string)(nil), "homophone", 0.5,
			"manual", OriginHuman, patch.StateProposed, (*string)(nil),
			(*time.Time)(nil), (*string)(nil), (*time.Time)(nil), createdAt,
			(*int)(nil), (*int)(nil), (*string)(nil),
			"",
		)

	mock.ExpectQuery("FROM transcript_findings").
		WithArgs((*string)(nil), (*string)(nil), (*string)(nil), []string(nil), 0.0,
			defaultCorrectionListLimit, 0).
		WillReturnRows(rows)

	got, err := database.listCorrections(context.Background(), mock, CorrectionFilter{})
	if err != nil {
		t.Fatalf("listCorrections: %v", err)
	}
	if len(got) != 2 {
		t.Fatalf("want 2 rows, got %d", len(got))
	}

	c0 := got[0]
	if c0.ID != "f1" || c0.TranscriptID != "t1" || c0.FilePath != "/books/a/b/ch1.m4b" || c0.BookDir != "/books/a/b" {
		t.Errorf("row 0 identity mis-scanned: %+v", c0)
	}
	if c0.ChunkID == nil || *c0.ChunkID != chunkID {
		t.Errorf("row 0 chunk id mis-scanned: %+v", c0.ChunkID)
	}
	if c0.ChunkIndex == nil || *c0.ChunkIndex != chunkIdx {
		t.Errorf("row 0 chunk index mis-scanned: %+v", c0.ChunkIndex)
	}
	if c0.SuggestedCorrection == nil || *c0.SuggestedCorrection != correction {
		t.Errorf("row 0 suggested correction mis-scanned: %+v", c0.SuggestedCorrection)
	}
	if c0.StaleReason == nil || *c0.StaleReason != staleReason {
		t.Errorf("row 0 stale reason mis-scanned: %+v", c0.StaleReason)
	}
	if c0.DecidedAt == nil || !c0.DecidedAt.Equal(decidedAt) {
		t.Errorf("row 0 decided_at mis-scanned: %+v", c0.DecidedAt)
	}
	if c0.DecidedBy == nil || *c0.DecidedBy != decidedBy {
		t.Errorf("row 0 decided_by mis-scanned: %+v", c0.DecidedBy)
	}
	if c0.AppliedAt == nil || !c0.AppliedAt.Equal(appliedAt) {
		t.Errorf("row 0 applied_at mis-scanned: %+v", c0.AppliedAt)
	}
	if !c0.CreatedAt.Equal(createdAt) {
		t.Errorf("row 0 created_at mis-scanned: %+v", c0.CreatedAt)
	}
	if c0.AnchorOffset == nil || *c0.AnchorOffset != off {
		t.Errorf("row 0 anchor offset mis-scanned: %+v", c0.AnchorOffset)
	}
	if c0.AnchorOccurrence == nil || *c0.AnchorOccurrence != occ {
		t.Errorf("row 0 anchor occurrence mis-scanned: %+v", c0.AnchorOccurrence)
	}
	if c0.ChunkTextSHA256 == nil || *c0.ChunkTextSHA256 != hash {
		t.Errorf("row 0 chunk hash mis-scanned: %+v", c0.ChunkTextSHA256)
	}
	if c0.ChunkText != "the auto sebo dish" {
		t.Errorf("row 0 chunk text mis-scanned: %q", c0.ChunkText)
	}

	c1 := got[1]
	if c1.ChunkID != nil || c1.ChunkIndex != nil || c1.SuggestedCorrection != nil ||
		c1.StaleReason != nil || c1.DecidedAt != nil || c1.DecidedBy != nil ||
		c1.AppliedAt != nil || c1.AnchorOffset != nil || c1.AnchorOccurrence != nil ||
		c1.ChunkTextSHA256 != nil {
		t.Errorf("row 1 should carry NULLs as nil pointers: %+v", c1)
	}
	if c1.ChunkText != "" {
		t.Errorf("row 1 (no chunk) should have empty chunk text, got %q", c1.ChunkText)
	}

	if err := mock.ExpectationsWereMet(); err != nil {
		t.Errorf("unmet expectations: %v", err)
	}
}

